function metrics = metricCatalog()
%METRICCATALOG Single-node metric labels and definitions for GUI and export.
% Values are replication-level statistics; summary means are across runs.
names = { ...
    'Avg. wait','P95 wait','Avg. total time (wait + service)', ...
    'Avg. queue length','Server busy rate','Rejection rate', ...
    'Chance of waiting','Throughput','Max. queue length', ...
    'Max. wait','Within wait target'};
fields = { ...
    'MeanWaitMin','P95WaitMin','MeanTimeInSystemMin', ...
    'MeanQueueLength','ServerBusyPct','RejectedPct', ...
    'WaitChancePct','ThroughputPerMin','MaxQueueLength', ...
    'MaxWaitMin','WithinTargetPct'};
units = {'min','min','min','people','%','%','%', ...
    'customers/min','people','min','%'};
help = { ...
    'Average queue wait among customers who started service.', ...
    'Within-run 95th percentile of observed waits; chart shows the mean of replication percentiles.', ...
    'Sojourn time: time from arrival at this queue/service node to completion. Excludes upstream shopping, travel, and other nodes.', ...
    'Time-average number of customers waiting, not in service.', ...
    'Mean fraction of time servers are busy in the observation window.', ...
    'Rejected arrivals divided by all arrivals; zero when none arrive.', ...
    'Share of accepted, service-started customers with a positive wait.', ...
    'Completions by the observation cutoff per minute; excludes drain tail.', ...
    'Largest simultaneous count waiting, not counting in-service customers.', ...
    'Average of each replication''s longest observed waiting time.', ...
    'Share of observed waits at or below the user-set target.'};
metrics = struct('name',names,'field',fields,'unit',units,'help',help);
end

function reportPath=writeM41Report(folder,a,b,c,bNodes,cNodes,staffing)
%WRITEM41REPORT Produce concise, reproducible Markdown A-C overview.
% a: M3.1 compared policies, b: B comparison, c: cell of C comparisons.
if ~exist(folder,'dir'), mkdir(folder); end
reportPath=fullfile(folder,'INTEGRATED_REPORT.md');
fid=fopen(reportPath,'wt');
if fid<0, error('qsim:ExportFailed','Cannot write integrated report.'); end
clean=onCleanup(@()fclose(fid));
fprintf(fid,'# QueueSimLab — Integrated Experiment Report (A–C)\n\n');
fprintf(fid,'Generated by `examples/run_m41_integrated.m` using MATLAB.\n\n');
fprintf(fid,'## Research logic\n\n');
fprintf(fid,['**Policy choice (A) → queueing-network bottlenecks (B) → ' ...
    'demand/topology stress (C) → resource decisions.**\n\n']);
fprintf(fid,'### Benchmark A: Single-node policy comparison\n\n');
fprintf(fid,'| Policy | Mean wait (min) | 95%% CI | P95 wait (min) |\n');
fprintf(fid,'|---|---:|---:|---:|\n');
for k=1:numel(a.summary)
    x=a.summary(k); w=x.metrics.meanWait; p=x.metrics.p95Wait;
    fprintf(fid,'| %s | %.3f | [%.3f, %.3f] | %.3f |\n', ...
        x.name,w.mean,w.lower,w.upper,p.mean);
end
fprintf(fid,'\n![A: waiting time](figures/A_waits.png)\n\n');
fprintf(fid,'### Benchmark B: Where to add one server?\n\n');
fprintf(fid,'| Choice | Journey (min) | Paired gain vs baseline (min) | 95%% CI of gain |\n');
fprintf(fid,'|---|---:|---:|---:|\n');
for k=1:height(staffing)
    fprintf(fid,'| %s | %.3f | %+.3f | [%.3f, %.3f] |\n', ...
        staffing.scenario{k},staffing.scenarioJourneyMin(k), ...
        staffing.pairedGainMin(k),staffing.gainCI_Lower(k), ...
        staffing.gainCI_Upper(k));
end
fprintf(fid,'\n![B: network map](figures/B_network_diagnostics.png)\n\n');
fprintf(fid,'![B: paired staffing gain](figures/B_paired_staffing_gain.png)\n\n');
fprintf(fid,'**B baseline theoretical node intensities** (unthrottled external flow):\n\n');
fprintf(fid,'| Node | λ expected (visits/min) | Capacity (visits/min) | Offered load | Simulated wait (min) |\n');
fprintf(fid,'|---|---:|---:|---:|---:|\n');
for v=1:numel(b.nodeIds)
    ix=strcmp(bNodes.scenario,b.scenarioNames{1}) & ...
        strcmp(bNodes.node,b.nodeIds{v});
    fprintf(fid,'| %s | %.3f | %.3f | %.2f | %.3f |\n', ...
        b.nodeIds{v},bNodes.theoreticalRatePerMin(ix), ...
        bNodes.nominalCapacityPerMin(ix), ...
        bNodes.offeredLoad(ix),bNodes.meanNodeWaitMin(ix));
end
fprintf(fid,'\n### Benchmark C: Topology and demand stress\n\n');
fprintf(fid,'| External arrivals/min | Topology | Mean journey (min) | 95%% CI | Max node offered load |\n');
fprintf(fid,'|---:|---|---:|---:|---:|\n');
for k=1:numel(c)
    res=c{k};
    for aIdx=1:numel(res.scenarioNames)
        x=res.summary(aIdx).metrics.meanEndToEndSojourn;
        mask=cNodes.demandLevel==k & strcmp(cNodes.scenario,res.scenarioNames{aIdx});
        maxLoad=max(cNodes.offeredLoad(mask));
        fprintf(fid,'| %.2f | %s | %.3f | [%.3f, %.3f] | %.2f%s |\n', ...
            cNodes.arrivalRatePerMin(find(mask,1)),res.scenarioNames{aIdx}, ...
            x.mean,x.lower,x.upper,maxLoad,overloadSuffix(maxLoad));
    end
end
fprintf(fid,'\n![C: network demand sensitivity](figures/C_demand_response.png)\n\n');
fprintf(fid,'## Flow integrity and statistical scope\n\n');
fprintf(fid,['- Exact integer flow conservation checked for every drained ' ...
    'network replication (node arrival, admission and exit balances).\n']);
fprintf(fid,['- Theoretical node rates are **expected** unthrottled ' ...
    'flows; realized branch counts fluctuate and may differ from the expectation.\n']);
fprintf(fid,['- A and B compare matched scenarios; B gain CIs use ' ...
    '**within-seed differences** with identical demand and per-node service laws.\n']);
fprintf(fid,['- C compares **different network routing/work allocation**; ' ...
    'the plotted CIs are replication means, not a causal topology effect estimate.\n']);
fprintf(fid,['- The sample unit is one independent replication. ' ...
    'Runs begin empty, with a finite arrival horizon and drain mode. ' ...
    'Reported utilization is over the observation horizon.\n']);
fprintf(fid,['- Nominal offered load at or above 1 means a node would be ' ...
    'overloaded in a sustained-arrival interpretation. Large finite-horizon ' ...
    'delays are **not steady-state waiting-time estimates**.\n']);
fprintf(fid,['- No backpressure, loops, dynamic shared resources, ' ...
    'spatial traffic queues or EV charging coupling are implemented in V0.2.\n\n']);
fprintf(fid,'## Machine-readable data\n\n');
fprintf(fid,['`integrated_metrics.csv`, `B_node_diagnostics.csv`, ' ...
    '`B_staffing_paired.csv`, `C_node_diagnostics.csv`, ' ...
    '`C_scenario_metrics.csv`, and `m41_results.mat`.\n']);
end
function txt=overloadSuffix(load)
if load>=1, txt=' **OVERLOAD**'; else, txt=''; end
end

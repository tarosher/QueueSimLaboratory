function verifyM41Artifacts(folder,expectedNodeDiagnostics)
%VERIFYM41ARTIFACTS Assert the full M4.1 report/export pipeline completed.
% Unlike unit tests of individual modules, this guards against a partially
% written project-level integrated result directory.
required={'INTEGRATED_REPORT.md','integrated_metrics.csv', ...
    'B_node_diagnostics.csv','B_staffing_paired.csv', ...
    'C_node_diagnostics.csv','C_scenario_metrics.csv','m41_results.mat', ...
    fullfile('figures','A_waits.png'), ...
    fullfile('figures','B_network_diagnostics.png'), ...
    fullfile('figures','B_paired_staffing_gain.png'), ...
    fullfile('figures','C_demand_response.png')};
for k=1:numel(required)
    p=fullfile(folder,required{k});
    info=dir(p);
    if numel(info)~=1 || info.bytes==0
        error('qsim:ExportFailed','Missing or empty M4.1 artifact: %s',p);
    end
end
actual=readtable(fullfile(folder,'C_node_diagnostics.csv'));
if height(actual)~=height(expectedNodeDiagnostics) || ...
        ~all(ismember({'demandLevel','arrivalRatePerMin'}, ...
        actual.Properties.VariableNames)) || ...
        ~isequal(actual.demandLevel,expectedNodeDiagnostics.demandLevel) || ...
        ~isequal(size(actual.arrivalRatePerMin), ...
        size(expectedNodeDiagnostics.arrivalRatePerMin)) || ...
        any(abs(actual.arrivalRatePerMin - ...
        expectedNodeDiagnostics.arrivalRatePerMin)>1e-10)
    error('qsim:ExportFailed','C node diagnostics CSV does not match expected rows.');
end
report=fileread(fullfile(folder,'INTEGRATED_REPORT.md'));
if ~contains(report,'### Benchmark A:') || ...
        ~contains(report,'### Benchmark B:') || ...
        ~contains(report,'### Benchmark C:')
    error('qsim:ExportFailed','Integrated report is missing a benchmark section.');
end
end
